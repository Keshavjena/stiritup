#!/usr/bin/env python3
"""Emit TypeScript seed files (one per category) + index + types from personalities.json."""
import json, os, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
SEED = os.path.join(SRC, "seed")
CATS = ["bollywood", "hollywood", "actors", "singers", "athletes", "scientists",
        "tech", "models", "creators", "glamour", "history", "writers", "artists", "fantasy", "icons"]

TITLES = {c: c.capitalize() for c in CATS}
TITLES.update({"glamour": "GlamourModels", "tech": "Tech", "creators": "Creators"})

def js(o):
    return json.dumps(o, ensure_ascii=False)

OPT_IN = {"scientists", "history"}


def main():
    data = json.load(open(os.path.join(ROOT, "data", "personalities.json")))
    os.makedirs(SEED, exist_ok=True)
    groups = collections.OrderedDict((c, []) for c in CATS)
    for r in data:
        groups[r["category"]].append(r)

    header = "// AUTO-GENERATED by scripts/gen_ts.py - do not edit by hand.\n"
    CHUNK = 1200
    for cat, rows in groups.items():
        var = TITLES[cat]
        lines = [header, 'import type { Personality } from "../types"\n\n']
        # emit in chunks: a single 5k-element literal makes TypeScript's type checker explode
        parts = [rows[i:i + CHUNK] for i in range(0, len(rows), CHUNK)] or [[]]
        for idx, part in enumerate(parts):
            lines.append(f"const chunk{idx}: Personality[] = [\n")
            for r in part:
                lines.append(
                    "  { " + f'id: {js(r["id"])}, name: {js(r["name"])}, gender: {js(r["gender"])}, '
                    f'category: {js(r["category"])}, tags: {js(r["tags"])}, '
                    f'description: {js(r["description"])}, image: {js(r["image"])}, '
                    f'popularity: {r["popularity"]}, country: {js(r["country"])}, '
                    f'birthYear: {js(r["birthYear"])}, occupations: {js(r["occupations"])}, '
                    f'aliases: {js(r["aliases"])}, tier: {js(r["tier"])}, '
                    f'workFame: {r["workFame"]}, optIn: {str(r["optIn"]).lower()}, '
                    f'age: {js(r["age"])}, deathYear: {js(r["deathYear"])}, beauty: {r["beauty"]}, '
                    f'visual: {str(r["visual"]).lower()} }},\n')
            lines.append("]\n\n")
        lines.append(f"export const {var}: Personality[] = [\n")
        lines.append("  " + ", ".join(f"...chunk{i}" for i in range(len(parts))) + ",\n]\n")
        open(os.path.join(SEED, f"{cat}.ts"), "w").write("".join(lines))
        jsdir = os.path.join(ROOT, "data", "json")
        os.makedirs(jsdir, exist_ok=True)
        json.dump(rows, open(os.path.join(jsdir, f"{cat}.json"), "w"), ensure_ascii=False, separators=(",", ":"))

    idx = [header, 'import type { Personality } from "./types"\n']
    for cat in CATS:
        idx.append(f'import {{ {TITLES[cat]} }} from "./seed/{cat}"\n')
    idx.append("\n/** Every seeded personality, grouped by category. */\n")
    idx.append("export const PERSONALITIES_BY_CATEGORY: Record<string, Personality[]> = {\n")
    for cat in CATS:
        idx.append(f'  {cat}: {TITLES[cat]},\n')
    idx.append("}\n\n")
    idx.append("/** Categories that are opt-in only (never part of a default round). */\n")
    idx.append("export const OPT_IN_CATEGORIES = [\"scientists\", \"history\"] as const\n\n")
    idx.append("/** The default pool: everyone visual (models, actors, athletes, creators...) except opt-ins. */\n")
    idx.append("export const EXPANDED_PERSONALITIES: Personality[] = (\n")
    idx.append("  [" + ", ".join(f"...{TITLES[c]}" for c in CATS if c not in OPT_IN) + "]\n")
    idx.append(").filter((p) => p.visual)\n\n")
    idx.append("/** Recognisable but not a looks-based round: writers, tech, icons. */\n")
    idx.append("export const NON_VISUAL_PERSONALITIES: Personality[] = (\n")
    idx.append("  [" + ", ".join(f"...{TITLES[c]}" for c in CATS if c not in OPT_IN) + "]\n")
    idx.append(").filter((p) => !p.visual)\n\n")
    idx.append("/** The opt-in pool (scientists + history, A+ tier only). Use only on request. */\n")
    idx.append("export const OPT_IN_PERSONALITIES: Personality[] = [\n")
    idx.append("  " + ", ".join(f"...{TITLES[c]}" for c in CATS if c in OPT_IN) + ",\n]\n\n")
    idx.append("/** Everything: default pool + non-visual + opt-in. */\n")
    idx.append("export const ALL_PERSONALITIES: Personality[] = [\n")
    idx.append("  ...EXPANDED_PERSONALITIES,\n  ...NON_VISUAL_PERSONALITIES,\n  ...OPT_IN_PERSONALITIES,\n]\n\n")
    idx.append("""export function byCategory(category: string): Personality[] {
  return PERSONALITIES_BY_CATEGORY[category] ?? []
}

export function byGender(gender: string): Personality[] {
  return EXPANDED_PERSONALITIES.filter((p) => p.gender === gender)
}

/** Appearance-forward pool only (beauty 2: models, adult performers, pageant winners). */
export function beautyFirst(): Personality[] {
  return EXPANDED_PERSONALITIES.filter((p) => p.beauty === 2)
}

/** A+ (household names) only. */
export function aPlus(includeOptIn = false): Personality[] {
  const pool = includeOptIn ? ALL_PERSONALITIES : EXPANDED_PERSONALITIES
  return pool.filter((p) => p.tier === "A+")
}

/**
 * Random sample of `n` distinct personalities.
 * Pass `{ includeOptIn: true }` (or a category named "scientists" / "history") to use the
 * opt-in pool - those categories are excluded by default.
 */
export function sample(n: number, filter?: (p: Personality) => boolean, opts: { includeOptIn?: boolean } = {}): Personality[] {
  const pool = (opts.includeOptIn ? ALL_PERSONALITIES : EXPANDED_PERSONALITIES)
    .filter(filter ?? (() => true)).slice()
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  return pool.slice(0, n)
}

/** Wikimedia Commons thumbnail URL at a given width. */
export function imageUrl(p: Personality, width = 480): string {
  if (!p.image) return ""
  return `${p.image}?width=${width}`
}

export type { Personality, Category, Gender, SeedPersonality } from "./types"
""")
    open(os.path.join(SRC, "index.ts"), "w").write("".join(idx))

    index = {c: len(v) for c, v in groups.items() if v}
    index["_total"] = len(data)
    json.dump(index, open(os.path.join(ROOT, "data", "json", "index.json"), "w"), indent=1)
    print("wrote seed files:", {c: len(v) for c, v in groups.items()})

if __name__ == "__main__":
    main()
