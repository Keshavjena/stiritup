#!/usr/bin/env python3
"""Emit TypeScript seed files (one per category) + index + types from personalities.json."""
import json, os, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
SEED = os.path.join(SRC, "seed")
CATS = ["bollywood", "hollywood", "actors", "singers", "athletes", "scientists",
        "tech", "models", "creators", "glamour", "history", "writers", "artists", "fantasy", "icons"]

TITLES = {c: c.capitalize() for c in CATS}
TITLES.update({"glamour": "GlamourModels", "tech": "Tech", "creators": "Creators"})

def js(o):
    return json.dumps(o, ensure_ascii=False)

def main():
    data = json.load(open(os.path.join(ROOT, "data", "personalities.json")))
    os.makedirs(SEED, exist_ok=True)
    groups = collections.OrderedDict((c, []) for c in CATS)
    for r in data:
        groups[r["category"]].append(r)

    header = "// AUTO-GENERATED by scripts/gen_ts.py - do not edit by hand.\n"
    for cat, rows in groups.items():
        var = TITLES[cat]
        lines = [header, 'import type { Personality } from "../types"\n\n',
                 f"export const {var}: Personality[] = [\n"]
        for r in rows:
            lines.append(
                "  { " + f'id: {js(r["id"])}, name: {js(r["name"])}, gender: {js(r["gender"])}, '
                f'category: {js(r["category"])}, tags: {js(r["tags"])}, '
                f'description: {js(r["description"])}, image: {js(r["image"])}, '
                f'popularity: {r["popularity"]}, country: {js(r["country"])}, '
                f'birthYear: {js(r["birthYear"])}, occupations: {js(r["occupations"])}, '
                f'aliases: {js(r["aliases"])} }},\n')
        lines.append("]\n")
        open(os.path.join(SEED, f"{cat}.ts"), "w").write("".join(lines))
        jsdir = os.path.join(ROOT, "data", "json")
        os.makedirs(jsdir, exist_ok=True)
        json.dump(rows, open(os.path.join(jsdir, f"{cat}.json"), "w"), ensure_ascii=False, separators=(",", ":"))

    idx = [header, 'import type { Personality } from "./types"\n']
    for cat in CATS:
        idx.append(f'import {{ {TITLES[cat]} }} from "./seed/{cat}"\n')
    idx.append("\n/** Every seeded personality, grouped by category. */\n")
    idx.append("export const PERSONALITIES_BY_CATEGORY: Record<string, Personality[]> = {\n")
    for cat in CATS:
        idx.append(f'  {cat}: {TITLES[cat]},\n')
    idx.append("}\n\n/** Flat list of all personalities (alias kept for backwards compatibility). */\n")
    idx.append("export const EXPANDED_PERSONALITIES: Personality[] = [\n")
    idx.append("  " + ", ".join(f"...{TITLES[c]}" for c in CATS) + ",\n]\n\n")
    idx.append("""export const ALL_PERSONALITIES = EXPANDED_PERSONALITIES

export function byCategory(category: string): Personality[] {
  return PERSONALITIES_BY_CATEGORY[category] ?? []
}

export function byGender(gender: string): Personality[] {
  return ALL_PERSONALITIES.filter((p) => p.gender === gender)
}

/** Random sample of `n` distinct personalities, optionally filtered. */
export function sample(n: number, filter?: (p: Personality) => boolean): Personality[] {
  const pool = filter ? ALL_PERSONALITIES.filter(filter) : [...ALL_PERSONALITIES]
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  return pool.slice(0, n)
}

/** Wikimedia Commons thumbnail URL at a given width. */
export function imageUrl(p: Personality, width = 480): string {
  if (!p.image) return ""
  return `${p.image}?width=${width}`
}

export type { Personality, Category, Gender, SeedPersonality } from "./types"
""")
    open(os.path.join(SRC, "index.ts"), "w").write("".join(idx))

    index = {c: len(v) for c, v in groups.items() if v}
    index["_total"] = len(data)
    json.dump(index, open(os.path.join(ROOT, "data", "json", "index.json"), "w"), indent=1)
    print("wrote seed files:", {c: len(v) for c, v in groups.items()})

if __name__ == "__main__":
    main()
